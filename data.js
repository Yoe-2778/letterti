export function calculateResult(answers) {
  if (!Array.isArray(answers) || answers.length !== questions.length || Array.from(answers).some(a => !Number.isInteger(a) || a < 0 || a > 3)) {
    throw new Error('请完成全部24道题后再生成说明书。');
  }
  const sums = [0, 0, 0, 0];
  questions.forEach((q, i) => { sums[q.dimension] += [3, 1, -1, -3][answers[i]] * q.direction; });
  const scores = sums.map(n => Math.round((18 - n) / 36 * 100));
  const sides = sums.map(n => n < 0 ? 1 : 0);
  const balanced = sums.map(n => Math.abs(n) <= 4);
  const type = sides.reduce((n, side) => n * 2 + side, 0);
  return { scores, sides, balanced, type, name: archetypes[type][0], subtitle: archetypes[type][1] };
}
